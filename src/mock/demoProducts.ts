export function searchDemoProducts(query: string, category?: string): MarketplaceProduct[] {
  const normalizedQuery = query.toLowerCase().trim();
  const now = new Date().toISOString();

  let results = DEMO_PRODUCTS.map((prod) => ({
    ...prod,
    queryTimestamp: now,
  }));

  if (category && category !== 'Todos') {
    const catLower = category.toLowerCase();
    if (catLower.includes('perfume')) {
      results = results.filter((p) => p.id.includes('PERF') || p.title.toLowerCase().includes('perfume') || p.title.toLowerCase().includes('colônia'));
    } else if (catLower.includes('beleza')) {
      results = results.filter((p) => p.id.includes('BEL') || p.title.toLowerCase().includes('secador') || p.title.toLowerCase().includes('cerave'));
    } else if (catLower.includes('eletrônico')) {
      results = results.filter((p) => p.id.includes('ELET') || p.title.toLowerCase().includes('iphone') || p.title.toLowerCase().includes('jbl') || p.title.toLowerCase().includes('xiaomi'));
    } else if (catLower.includes('casa')) {
      results = results.filter((p) => p.id.includes('CASA') || p.title.toLowerCase().includes('air fryer') || p.title.toLowerCase().includes('cafeteira') || p.title.toLowerCase().includes('wap'));
    }
  }

  if (normalizedQuery) {
    const terms = normalizedQuery.split(/\s+/).filter(Boolean);
    results = results.filter((product) => {
      const targetText = `${product.title} ${product.seller.name} ${product.attributes.map((a) => `${a.name} ${a.value_name}`).join(' ')}`.toLowerCase();
      return terms.some((term) => targetText.includes(term));
    });
  }

  return results;
}
